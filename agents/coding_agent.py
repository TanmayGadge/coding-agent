class CodingAgentState(BaseModel):
    messages: Annotated[list[BaseMessage], add_messages]
    coding_plan: str
    code: str
    code_path: str
    code_feedback: Optional[list[ActionableIssue]] = None
    coder_retries: int = 0
    
    
def coding_agent_node(state: CodingAgentState):
    coding_plan = state.coding_plan
    global CODER_ITERATIONS
    
    system_msg = SystemMessage(
        content="You are a Senior Software Engineer agent.\n"
        "Your job is to take the detailed implementation plan generated by the Lead Software architect agent and write Python code to implement it.\n"
        "DON'T make any changes to the implementation plan or make any assumptions. Only follow the plan\n"
        "Write the python code in a single file and follow best practices like:\n"
        "1. Use clear, descriptive names for variables (nouns like userAge), functions (verbs like calculateTotal), and classes instead of cryptic shortcuts like 'x' or 'foo'\n"
        "2. Single Responsibility Principle (SRP): Keep functions and classes small (typically 20 to 30 lines) so each unit does only one specific job\n"
        "3. Low Complexity: Avoid deep nesting of loops or conditional statements by using patterns like 'guarded early returns' to keep the main logic left-aligned\n"
        "4. Choose algorithms with lower time and space complexity (Big-O), and pick the right data structure (such as using a hash map or dictionary for O(1) lookups instead of repeatedly iterating over a list)\n"
        "5. Consistent Formatting: Use uniform indentation and spacing."
        "6. Add comments to important parts of the code to explain what you did. Make sure the comments aren't too long (1-2 lines are appropriate).\n"
        "If code testing agent's feedback is provided, implement the chages to the code."
    )
     
   
    
    if state.code_feedback:
        # feedback_prompt = f"\nconsider the following feedback given by the code tester and make changes to address all the issues.\nCode Feedback(separated by triple backticks):\n ```{state.code_feedback}```"
        
        
        user_prompt = HumanMessage(
            content="Consider the code you wrote and the changes suggested by the testing agent and implement those changes.\n"
            "The code(separated by triple backticks):\n"
            f"```{state.code}```\n"
            "The feedback(separated by triple backticks):\n"
            f"```{state.code_feedback}```"
        )
        
    else:
        user_prompt = f"""Take the following plan and implement it:\n
            Coding plan (separated by triple backticks):
            ```
            {coding_plan}
            ```
        """
    
    if state.coder_retries <= 5:
        print(f'\n[Coding Node]: CODER_ITERATIONS = {CODER_ITERATIONS}')
        response = model.invoke([system_msg, user_prompt] + state.messages)
        retries = state.coder_retries + 1
        return {'messages': [response], "coder_retries": retries}
    else:
        print("Max iterations hit.\nExiting Coding node...")
        ai_msg = AIMessage(content="Max coding iterations(5) have been reached. No changes made to the code, please don't apply further tests.")
        return {"messages": [ai_msg]}
    
class CodeOutputStructure(BaseModel):
    code: str = Field("The python code generated by the model")
    
def structure_agent_node(state: CodingAgentState):
    system_msg = SystemMessage(
        content="You are a code structuring agent\n"
        "Your job is to just extract the code from the model's response.\n"
        "Don't make any changes to the code just return the code in the specified format.\n"
    )
    
    structured_model = model.with_structured_output(CodeOutputStructure)
    
    response = cast(CodeOutputStructure, structured_model.invoke([system_msg] + state.messages))
    
    ai_msg = AIMessage(content=str(response))
    
    return {'code': response.code, 'messages': [ai_msg]}

class FileAgentOutput(BaseModel):
    filename: str = Field(default="", description="The filename based on the coding/implementation plan.")

def save_code_in_file(state: CodingAgentState):
    global SCRIPT_DIR
    code = state.code
    code_path = state.code_path
    
    if code_path and len(str(code_path).strip()) > 0:
        absolute_code_filepath = Path(code_path)
        with open(absolute_code_filepath, 'w', encoding='utf-8') as file:
            file.write(code)
        file.close()
        
        print(f"Code written to {absolute_code_filepath} successfully!")
        
        return {"code_path": str(absolute_code_filepath)}
    else:
        system_msg = SystemMessage(
            content="You are a file naming agent.\n"
            "Your job to to create a dynamic filename for the python code file based on the given coding plan.\n"
            "Make sure that the file name is short, readable and relevant to the actual coding plan provided by the user.\n"
            "Follow the following naming convention for the python code file:\n"
            "1. Follow the snake_case convention.\n"
            "2. Use underscores to separate multiple words (e.g. kv_cache_store.py).\n"
            "3. Keep it short. It is highly preferable to stick to short, concise, one-word or two-word names.\n"
            "4. DON'T add the '.py' file extention at the end.\n"
            "5. Keep all the letters in filename strictly lowercase.\n"
            "6. NEVER use hyphens or dashes (-) to separate multiple words in a filename. Only use underscores\n"
            "7. If the coding plan is for a profile finder app, then keep the filename as [platform_name]_profile_finder (e.g. facebook_profile_finde)\n"
        )
        
        user_msg = HumanMessage(
            content="Take the following coding plan and create a filename for it.\n"
            "Coding plan(separated by triple backticks):\n"
            f"```{state.coding_plan}```"
        )
        
        structured_model = model.with_structured_output(FileAgentOutput)
        response = cast(FileAgentOutput, structured_model.invoke([system_msg, user_msg]))
        file_name = response.filename
        
        relative_filepath = f"../workspace/code_files/{file_name}.py"
        absolute_code_filepath = (SCRIPT_DIR / relative_filepath).resolve()
        
        with open(absolute_code_filepath, 'w', encoding='utf-8') as file:
            file.write(code)
        file.close()
        
        print(f"Code written to {absolute_code_filepath} successfully!")
        
        return {"code_path": str(absolute_code_filepath)}
        
    
    
graph = StateGraph(CodingAgentState)
graph.add_node('coding_agent', coding_agent_node)
graph.add_node('structure_agent', structure_agent_node)
graph.add_node('file_saver', save_code_in_file)

graph.add_edge(START, 'coding_agent')
graph.add_edge('coding_agent', 'structure_agent')
graph.add_edge('structure_agent', 'file_saver')
graph.add_edge('file_saver', END)



